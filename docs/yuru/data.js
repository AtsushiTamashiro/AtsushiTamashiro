  function seeded(n) {
    let s = (n * 9301 + 49297) % 233280;
    return () => { s = (s * 9301 + 49297) % 233280; return s / 233280; };
  }
  function mkStats(i, boost) {
    const r = seeded(i + 7);
    const pts = [r(), r(), r(), r()].map(v => 0.6 + v);
    const sum = pts.reduce((a, b) => a + b, 0);
    const total = 320 * boost;
    const [hp, atk, def, spd] = pts.map(p => Math.round(total * p / sum));
    return { hp: Math.max(60, hp), atk: Math.max(55, atk), def: Math.max(55, def), spd: Math.max(45, spd) };
  }
